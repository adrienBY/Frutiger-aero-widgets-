"""Write the animated bubble layers for the weather widget.

Usage: python3 design/make_bubbles.py <res-dir>
Produces drawable/wx_bubbles_day.xml and wx_bubbles_night.xml: animated vectors in the
380-unit frame of design/weather.html. Each bubble rises from the hill, wobbles and fades.
A ProgressBar in the widget layout runs them, since widgets can't start animations themselves.
"""
import os
import sys

# (x centre, size, rise duration ms, start offset ms) in frame units
BUBBLES = [(224, 28, 6200, 0), (266, 16, 4600, 1200), (202, 12, 3800, 2400), (298, 10, 4200, 600),
           (244, 20, 5400, 3000), (284, 24, 6800, 2000), (230, 9, 3400, 1800), (318, 13, 5000, 3600)]
Y0, Y1 = 268, 150


def circle(cx, cy, r):
    return f'M{cx - r:.2f},{cy:.2f} a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0 a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0'


def avd(alpha):
    groups, anims = [], []
    for i, (x, s, dur, off) in enumerate(BUBBLES):
        r = s / 2
        hx, hy, hr = x - r * 0.32, Y0 - r * 0.36, r * 0.42
        rim = s >= 20
        paths = [f'''
      <path android:name="ring{i}" android:pathData="{circle(x, Y0, r - 0.75)}"
          android:strokeColor="#FFFFFFFF" android:strokeWidth="{1.5 if s >= 16 else 1}" android:strokeAlpha="0"/>''',
                 f'''
      <path android:name="hi{i}" android:pathData="{circle(hx, hy, hr)}" android:fillAlpha="0">
        <aapt:attr name="android:fillColor">
          <gradient android:type="radial" android:centerX="{hx:.2f}" android:centerY="{hy:.2f}"
              android:gradientRadius="{hr:.2f}" android:startColor="#F2FFFFFF" android:endColor="#00FFFFFF"/>
        </aapt:attr>
      </path>''']
        if rim:
            paths.append(f'''
      <path android:name="rim{i}" android:pathData="{circle(x, Y0, r - 1)}" android:fillAlpha="0">
        <aapt:attr name="android:fillColor">
          <gradient android:type="radial" android:centerX="{x}" android:centerY="{Y0}"
              android:gradientRadius="{r:.2f}" android:startColor="#00FFFFFF"
              android:centerColor="#00FFFFFF" android:endColor="#66C8FFFA"/>
        </aapt:attr>
      </path>''')
        groups.append(f'''
    <group android:name="b{i}">{''.join(paths)}
    </group>''')

        wob = 3 + s / 8
        move = f'''
  <target android:name="b{i}">
    <aapt:attr name="android:animation">
      <set>
        <objectAnimator android:propertyName="translateY" android:duration="{dur}" android:startOffset="{off}"
            android:valueFrom="0" android:valueTo="{Y1 - Y0}" android:valueType="floatType"
            android:repeatCount="infinite" android:interpolator="@android:interpolator/linear"/>
        <objectAnimator android:duration="{dur}" android:startOffset="{off}" android:repeatCount="infinite"
            android:interpolator="@android:interpolator/linear">
          <propertyValuesHolder android:propertyName="translateX">
            <keyframe android:fraction="0" android:value="0"/>
            <keyframe android:fraction="0.25" android:value="{wob:.1f}"/>
            <keyframe android:fraction="0.75" android:value="{-wob:.1f}"/>
            <keyframe android:fraction="1" android:value="0"/>
          </propertyValuesHolder>
        </objectAnimator>
      </set>
    </aapt:attr>
  </target>'''
        anims.append(move)
        names = [('ring', 'strokeAlpha', 0.72), ('hi', 'fillAlpha', 1.0)] + ([('rim', 'fillAlpha', 1.0)] if rim else [])
        for n, prop, peak in names:
            a = peak * alpha
            anims.append(f'''
  <target android:name="{n}{i}">
    <aapt:attr name="android:animation">
      <objectAnimator android:duration="{dur}" android:startOffset="{off}" android:repeatCount="infinite"
          android:interpolator="@android:interpolator/linear">
        <propertyValuesHolder android:propertyName="{prop}">
          <keyframe android:fraction="0" android:value="0"/>
          <keyframe android:fraction="0.18" android:value="{a:.3f}"/>
          <keyframe android:fraction="0.65" android:value="{a:.3f}"/>
          <keyframe android:fraction="1" android:value="0"/>
        </propertyValuesHolder>
      </objectAnimator>
    </aapt:attr>
  </target>''')

    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/make_bubbles.py -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt">
  <aapt:attr name="android:drawable">
    <vector android:width="190dp" android:height="190dp"
        android:viewportWidth="380" android:viewportHeight="380">{''.join(groups)}
    </vector>
  </aapt:attr>{''.join(anims)}
</animated-vector>
'''


out = os.path.join(sys.argv[1], 'drawable')
os.makedirs(out, exist_ok=True)
for name, alpha in (('day', 1.0), ('night', 0.55)):
    with open(os.path.join(out, f'wx_bubbles_{name}.xml'), 'w') as f:
        f.write(avd(alpha))
